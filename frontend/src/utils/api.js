import axios from 'axios'

const baseURL = import.meta.env.VITE_API_URL || ''
axios.defaults.baseURL = baseURL

export const api = {
  login: (d) => axios.post('/api/auth/login', d),
  getProducts: () => axios.get('/api/products'),
  createProduct: (d) => axios.post('/api/products', d),
  getInventarioHoy: () => axios.get('/api/inventario/hoy'),
  registrarInventarioInicial: (d) => axios.post('/api/inventario/inicial', d),
  registrarInventarioFinal: (d) => axios.post('/api/inventario/final', d),
  solicitarInicioCero: () => axios.post('/api/inventario/solicitar-cero'),
  getSolicitudesCero: () => axios.get('/api/inventario/solicitudes-cero'),
  aprobarSolicitudCero: (id) => axios.put(`/api/inventario/solicitudes-cero/${id}/aprobar`),
  solicitarCargue: (d) => axios.post('/api/cargue', d),
  getCarguesPendientes: () => axios.get('/api/cargue/pendientes'),
  getCargueVendedor: () => axios.get('/api/cargue/vendedor'),
  aprobarCargue: (id, cant) => axios.put(`/api/cargue/${id}/aprobar`, { cantidadAprobada: cant }),
  rechazarCargue: (id) => axios.put(`/api/cargue/${id}/rechazar`),
  calcularLiquidacion: () => axios.get('/api/liquidacion/calcular'),
  generarLiquidacion: () => axios.post('/api/liquidacion/generar'),
  getLiquidacionesVendedor: () => axios.get('/api/liquidacion/vendedor'),
  getDetalleLiquidacion: (id) => axios.get(`/api/liquidacion/${id}`),
  registrarPagos: (d) => axios.post('/api/pagos', d),
  getPagosPendientes: () => axios.get('/api/pagos/pendientes'),
  aceptarPago: (id) => axios.put(`/api/pagos/${id}/aceptar`),
  rechazarPago: (id) => axios.put(`/api/pagos/${id}/rechazar`),
  getPagosLiquidacion: (id) => axios.get(`/api/pagos/liquidacion/${id}`),
  registrarPNC: (d) => axios.post('/api/pnc', d),
  getPNCPendientes: () => axios.get('/api/pnc/pendientes'),
  validarPNC: (id) => axios.put(`/api/pnc/${id}/validar`),
  getPNCMes: (anio, mes) => axios.get(`/api/pnc/mes/${anio}/${mes}`),
  getDeudores: (params) => axios.get('/api/deudores', { params }),
  getDeudoresVendedor: () => axios.get('/api/deudores/vendedor'),
  marcarPagado: (id) => axios.put(`/api/deudores/${id}/pagar`),
  getPasivos: (params) => axios.get('/api/pasivos', { params }),
  crearPasivo: (d) => axios.post('/api/pasivos', d),
  eliminarPasivo: (id) => axios.delete(`/api/pasivos/${id}`),
  getStock: () => axios.get('/api/bodega/stock'),
  entradaBodega: (d) => axios.post('/api/bodega/entrada', d),
  cargueCliente: (d) => axios.post('/api/bodega/cargue-cliente', d),
  getDashboardAdmin: () => axios.get('/api/dashboard/admin'),
  getDashboardVendedor: () => axios.get('/api/dashboard/vendedor'),
  getVendedores: () => axios.get('/api/auth/vendedores'),
  register: (d) => axios.post('/api/auth/register', d),
  getSolicitudesNegativas: () => axios.get('/api/liquidacion/solicitudes-negativas'),
  aprobarNegativa: (id) => axios.put(`/api/liquidacion/solicitudes-negativas/${id}/aprobar`),
  rechazarNegativa: (id) => axios.put(`/api/liquidacion/solicitudes-negativas/${id}/rechazar`),
  getSolicitudNegativaVendedor: () => axios.get('/api/liquidacion/solicitudes-negativas-vendedor'),
  getInformeVendedor: (params) => axios.get('/api/informes/vendedor', { params }),
  getComisiones: (vendedorId, params) => axios.get(`/api/dashboard/comisiones/${vendedorId}`, { params }),
  pagarComision: (id) => axios.put(`/api/dashboard/comisiones/${id}/pagar`),
  desactivarUsuario: (id) => axios.put(`/api/auth/desactivar/${id}`),
  activarUsuario: (id) => axios.put(`/api/auth/activar/${id}`),
  getVendedoresTodos: () => axios.get('/api/auth/vendedores-todos'),
}

export const formatCOP = (v) =>
  new Intl.NumberFormat('es-CO', { style: 'currency', currency: 'COP', minimumFractionDigits: 0 }).format(v || 0)